# ============================================================
IMAGE_EDIT_USAGE_TEXT = """

##### 1. 使用法

1. 左側のサイドバーで，使用する画像修正モデルを選択します。

2. 出力サイズを選択します。  
   通常は `1024x1024` のままで構いません。

3. 修正したい画像を読み込みます。  
   方法は次の2つです。

   - パソコンから PNG / JPG / JPEG 画像をアップロードする
   - Inbox に保存済みの画像を読み込む

4. 画像が読み込まれると，「現在の処理対象画像（修正元）」として表示されます。

5. 「修正内容（プロンプト）」に，どのように修正したいかを入力します。

6. 「修正版を生成する」ボタンを押すと，AIが画像を修正します。

7. 修正された画像は，次の修正元になります。  
   これにより，何度でも連続して修正できます。

---

##### 2. 修正プロンプトの例

- 背景を夕焼けにしてください。
- 人物を削除して，背景だけを自然に補完してください。
- 全体を明るいビジネス資料向けの雰囲気にしてください。
- 色合いを青系に統一してください。
- 写真風ではなく，フラットなイラスト風にしてください。
- 余白を広げて，スライドの表紙に使いやすくしてください。

---

##### 3. 注意点

画像修正AIは，元画像を完全に維持したまま一部だけを正確に変更できるとは限りません。  
業務資料に利用する場合は，修正後の画像に不自然な点，不適切な表現，個人情報，権利上の問題がないか確認してください。

</div>
"""


